// Location: atlas/client/src/lib/engine/odyssey_blueprint_catalog.ts
// Odyssey Engineering Cross-Reference & Blueprint Catalog (Phase 10, Stage 10.2)
// Maps every on-foot Odyssey asset, good, and data item to suit upgrades, weapon upgrades,
// engineering modifications, and engineer unlock requirements.
// Classifies items as 'safe_to_sell', 'engineering_material', or 'engineer_unlock'.

export type OdysseyItemRole = 'safe_to_sell' | 'engineering_material' | 'engineer_unlock';

export interface OdysseyItemCrossReference {
  id: string; // internal normalized id (e.g. "catmedia")
  name: string; // formatted display name
  role: OdysseyItemRole;
  isSafeToSell: boolean;
  isCritical?: boolean; // True for ultra-rare/high-risk items (Manufacturing Instructions, Smear Campaign Plans, etc.)
  blueprints: string[]; // List of modification blueprints or upgrade recipes using this item
  engineerUnlocks: string[]; // List of engineer unlocks requiring this item
  safeToSellReason: string; // Explanatory text for player triage
}

export interface OdysseyBlueprintDefinition {
  id: string;
  name: string;
  category: 'suit_mod' | 'weapon_mod' | 'suit_upgrade' | 'weapon_upgrade' | 'engineer_unlock';
  description: string;
  targetSlot?: string;
  requiredMaterials: { itemId: string; count: number }[];
}

