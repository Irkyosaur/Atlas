/**
 * Helper to fetch cross-reference info for an item id (case-insensitive)
 */
export function getOdysseyItemCrossReference(rawId: string): OdysseyItemCrossReference {
  const normalizedId = rawId.toLowerCase().trim();
  const found = ODYSSEY_CROSS_REFERENCE_TABLE[normalizedId];
  if (found) return found;

  // Fallback for unlisted dynamic items: safe to sell if not matched
  return {
    id: normalizedId,
    name: rawId.replace(/([A-Z])/g, ' $1').replace(/_/g, ' ').trim(),
    role: 'safe_to_sell',
    isSafeToSell: true,
    blueprints: [],
    engineerUnlocks: [],
    safeToSellReason: 'Unknown or non-standard asset with zero matching engineering recipes. Safe for liquidation.',
  };
}
